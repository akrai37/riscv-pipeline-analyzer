#!/usr/bin/env python3
"""Runs every workload under every experiment configuration and writes the
results the README reports.

    scripts/run_experiments.py [--rvsim build/rvsim] [--out results]

Every run is checked in lockstep against the reference model (rvsim
--lockstep), so no number here comes from a run that diverged. Outputs:

    results/results.csv   one row per (workload, configuration)
    results/results.json  the same, with every counter rvsim reports
    results/summary.md    the tables and headline numbers in the README
    results/*.svg         charts (plain SVG, no plotting library needed)

Only the Python standard library is used.
"""

import argparse
import concurrent.futures
import csv
import json
import math
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORKLOADS = ["matmul", "qsort", "linked_list", "bsearch", "fib", "crc32", "memops"]

BASELINE = {"forwarding": True, "predictor": "2bit", "btb": 64, "pht": 256, "ras": 8,
            "mul": 3, "div": 32}

# Name -> changes from the baseline. Each experiment varies one mechanism.
CONFIGS = {
    "baseline": {},
    "no-forwarding": {"forwarding": False},
    "not-taken": {"predictor": "not-taken"},
    "btfn": {"predictor": "btfn"},
    "no-forwarding+not-taken": {"forwarding": False, "predictor": "not-taken"},
    "no-ras": {"ras": 0},
    "no-btb": {"btb": 0},
    "btb-4": {"btb": 4},
    "btb-16": {"btb": 16},
    "single-cycle-muldiv": {"mul": 1, "div": 1},
}

CONTROL_CAUSES = ["branch-mispredict", "jal-btb-miss", "jalr-mispredict", "return-mispredict"]


def rvsim_args(cfg):
    args = ["--predictor", cfg["predictor"], "--btb", str(cfg["btb"]), "--pht", str(cfg["pht"]),
            "--ras", str(cfg["ras"]), "--mul-latency", str(cfg["mul"]),
            "--div-latency", str(cfg["div"])]
    if not cfg["forwarding"]:
        args.append("--no-forwarding")
    return args


def run_one(rvsim, workload, name):
    cfg = {**BASELINE, **CONFIGS[name]}
    elf = os.path.join(ROOT, "workloads", "bin", f"{workload}.elf")
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "stats.json")
        proc = subprocess.run([rvsim, "--lockstep", "-q", "--json", out, *rvsim_args(cfg), elf],
                              capture_output=True, text=True)
        if proc.returncode != 0:
            raise RuntimeError(f"{workload} [{name}] failed (status {proc.returncode}):\n"
                               f"{proc.stdout}{proc.stderr}")
        stats = json.load(open(out))
    stats["workload"] = workload
    stats["experiment"] = name
    lost = stats["lost"]
    stats["control_lost"] = sum(lost[c] for c in CONTROL_CAUSES)
    stats["total_lost"] = sum(lost.values())
    assert stats["cycles"] == stats["instructions"] + stats["total_lost"]
    return stats


# --------------------------------------------------------------------------
# Tables

def pct(part, whole):
    return 100.0 * part / whole if whole else 0.0


def table(header, rows):
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" if i == 0 else "---:" for i in range(len(header))) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def summary(results):
    r = {(s["workload"], s["experiment"]): s for s in results}
    lines = ["# Results", "",
             "Generated by `scripts/run_experiments.py`. Every run below was checked in lockstep "
             "against the reference model.", ""]

    base_cfg = ", ".join(f"{k}={v}" for k, v in BASELINE.items())
    lines += ["## Baseline: where the cycles go", "", f"Configuration: {base_cfg}.", ""]
    rows = []
    for w in WORKLOADS:
        s = r[(w, "baseline")]
        n = s["instructions"]
        rows.append([f"`{w}`", f"{n:,}", f"{s['cycles']:,}", f"{s['cpi']:.3f}",
                     f"{s['lost']['load-use'] / n:.3f}", f"{s['lost']['mul/div'] / n:.3f}",
                     f"{s['control_lost'] / n:.3f}",
                     f"{pct(s['branch_mispredicts'], s['branches']):.1f}%"])
    lines += [table(["Workload", "Instructions", "Cycles", "CPI", "+ load-use", "+ mul/div",
                     "+ control flow", "Branch mispredict rate"], rows), "",
              "CPI = 1 + the three stall columns (fill and ecall serialization add under 0.0001).",
              ""]

    lines += ["## Forwarding", ""]
    rows = []
    tot_off = tot_on = dep_off = dep_on = 0
    for w in WORKLOADS:
        off, on = r[(w, "no-forwarding")], r[(w, "baseline")]
        d_off = off["lost"]["data-hazard"]
        d_on = on["lost"]["load-use"]
        dep_off += d_off
        dep_on += d_on
        tot_off += off["total_lost"]
        tot_on += on["total_lost"]
        rows.append([f"`{w}`", f"{off['cpi']:.3f}", f"{on['cpi']:.3f}",
                     f"{pct(off['cycles'] - on['cycles'], off['cycles']):.1f}%",
                     f"{d_off:,}", f"{d_on:,}", f"{pct(d_off - d_on, d_off):.1f}%"])
    lines += [table(["Workload", "CPI without", "CPI with", "Cycles saved",
                     "Data stalls without", "Data stalls with (load-use)", "Data stalls removed"],
                    rows), ""]

    lines += ["## Branch prediction", "",
              "All three share the 64-entry BTB for targets; they differ only in the direction "
              "chosen for conditional branches.", ""]
    rows = []
    for w in WORKLOADS:
        row = [f"`{w}`"]
        for e in ["not-taken", "btfn", "baseline"]:
            s = r[(w, e)]
            row.append(f"{pct(s['branch_mispredicts'], s['branches']):.1f}% / {s['cpi']:.3f}")
        rows.append(row)
    lines += [table(["Workload", "Not-taken", "BTFN", "2-bit"], rows), "",
              "Each cell: conditional-branch mispredict rate / CPI.", ""]

    lines += ["## Return address stack", ""]
    rows = []
    for w in WORKLOADS:
        no, yes = r[(w, "no-ras")], r[(w, "baseline")]
        rows.append([f"`{w}`", f"{yes['returns']:,}", f"{no['return_mispredicts']:,}",
                     f"{yes['return_mispredicts']:,}", f"{no['cpi']:.4f}", f"{yes['cpi']:.4f}"])
    lines += [table(["Workload", "Returns", "Mispredicted, no RAS", "Mispredicted, 8-entry RAS",
                     "CPI, no RAS", "CPI, RAS"], rows), ""]

    lines += ["## BTB size", ""]
    rows = []
    for w in WORKLOADS:
        rows.append([f"`{w}`"] + [f"{r[(w, e)]['cpi']:.3f}"
                                  for e in ["no-btb", "btb-4", "btb-16", "baseline"]])
    lines += [table(["Workload", "No BTB", "4 entries", "16 entries", "64 entries"], rows), ""]

    lines += ["## Multiply and divide latency", ""]
    rows = []
    for w in WORKLOADS:
        real, ideal = r[(w, "baseline")], r[(w, "single-cycle-muldiv")]
        rows.append([f"`{w}`", f"{real['muls']:,}", f"{real['divs']:,}", f"{real['cpi']:.3f}",
                     f"{ideal['cpi']:.3f}"])
    lines += [table(["Workload", "Multiplies", "Divides", "CPI, 3/32-cycle", "CPI, 1-cycle"],
                    rows), ""]

    geo = lambda xs: math.exp(sum(math.log(x) for x in xs) / len(xs))
    cpi_off = geo([r[(w, "no-forwarding")]["cpi"] for w in WORKLOADS])
    cpi_on = geo([r[(w, "baseline")]["cpi"] for w in WORKLOADS])
    cpi_simple = geo([r[(w, "no-forwarding+not-taken")]["cpi"] for w in WORKLOADS])
    headline = {
        "workloads": len(WORKLOADS),
        "configurations": len(CONFIGS),
        "data_stalls_removed_by_forwarding_pct": round(pct(dep_off - dep_on, dep_off), 1),
        "all_stall_cycles_removed_by_forwarding_pct": round(pct(tot_off - tot_on, tot_off), 1),
        "geomean_cpi_without_forwarding": round(cpi_off, 3),
        "geomean_cpi_baseline": round(cpi_on, 3),
        "geomean_cpi_no_forwarding_not_taken": round(cpi_simple, 3),
    }
    lines += ["## Headline numbers", "",
              f"- Forwarding removes {headline['data_stalls_removed_by_forwarding_pct']}% of "
              f"data-dependency stall cycles (data-hazard stalls without it vs load-use stalls "
              f"with it) and {headline['all_stall_cycles_removed_by_forwarding_pct']}% of all "
              f"stall cycles, across {len(WORKLOADS)} workloads.",
              f"- Geometric-mean CPI: {cpi_off:.3f} without forwarding, {cpi_on:.3f} with "
              f"(2-bit predictor in both); {cpi_simple:.3f} with neither forwarding nor a "
              "direction predictor.", ""]
    return "\n".join(lines), headline


