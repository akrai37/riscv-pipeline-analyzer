# Charts: horizontal bars in plain SVG, light and dark from one file.

LIGHT = {"surface": "#fcfcfb", "ink": "#0b0b0b", "ink2": "#52514e", "muted": "#898781",
         "grid": "#e1e0d9", "axis": "#c3c2b7", "base": "#c3c2b7",
         "s1": "#2a78d6", "s2": "#eb6834", "s3": "#1baf7a"}
DARK = {"surface": "#1a1a19", "ink": "#f0efec", "ink2": "#c3c2b7", "muted": "#898781",
        "grid": "#2c2c2a", "axis": "#383835", "base": "#52514e",
        "s1": "#3987e5", "s2": "#d95926", "s3": "#199e70"}

FONT = 'system-ui, -apple-system, "Segoe UI", sans-serif'


def style():
    def rules(p):
        return "".join(f".{k}{{fill:{v}}}" for k, v in p.items()) + \
            f".gridline{{stroke:{p['grid']}}}.baseline{{stroke:{p['axis']}}}"
    return (f"<style>text{{font-family:{FONT}}}{rules(LIGHT)}"
            f"@media (prefers-color-scheme: dark){{{rules(DARK)}}}</style>")


def nice_ticks(vmax, target=5):
    raw = vmax / target
    mag = 10 ** math.floor(math.log10(raw))
    step = next(m * mag for m in (1, 2, 2.5, 5, 10) if m * mag >= raw)
    n = math.ceil(vmax / step - 1e-9)
    return [round(i * step, 10) for i in range(n + 1)]


def bar_path(x, y, w, h, radius=4):
    """A bar from the baseline at x, square there, with a rounded data end."""
    if w <= 0:
        return ""
    r = min(radius, w, h / 2)
    return (f"M{x:.1f},{y:.1f}h{w - r:.1f}a{r},{r} 0 0 1 {r},{r}v{h - 2 * r:.1f}"
            f"a{r},{r} 0 0 1 {-r},{r}h{-(w - r):.1f}z")


def hbar_chart(title, subtitle, categories, series, *, stacked, fmt, x_label, x_start=0.0,
               note=None):
    """series: list of (name, color class, values). Stacked: segments left to
    right, rounded only at the end of the whole bar. Grouped: one bar per
    series per category."""
    width, left, right = 760, 112, 64
    plot_w = width - left - right
    bar_h = 14 if not stacked else 20
    gap = 2
    group_h = bar_h * (1 if stacked else len(series)) + gap * (0 if stacked else len(series) - 1)
    row_h = group_h + 18
    top = 78 if len(series) > 1 else 58
    height = top + row_h * len(categories) + 46 + (18 if note else 0)

    totals = [sum(s[2][i] for s in series) for i in range(len(categories))] if stacked else \
        [max(s[2][i] for s in series) for i in range(len(categories))]
    ticks = nice_ticks(max(totals) - x_start)
    ticks = [x_start + t for t in ticks]
    x_max = ticks[-1]
    sx = lambda v: left + (v - x_start) / (x_max - x_start) * plot_w

    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
           f'width="{width}" height="{height}" role="img" aria-label="{title}">', style(),
           f'<rect class="surface" x="0" y="0" width="{width}" height="{height}" rx="8"/>',
           f'<text class="ink" x="16" y="26" font-size="15" font-weight="600">{title}</text>',
           f'<text class="ink2" x="16" y="45" font-size="12">{subtitle}</text>']

    if len(series) > 1:
        lx = 16
        for name, cls, _ in series:
            out.append(f'<rect class="{cls}" x="{lx}" y="56" width="10" height="10" rx="2"/>')
            out.append(f'<text class="ink2" x="{lx + 15}" y="65" font-size="12">{name}</text>')
            lx += 15 + 7 * len(name) + 22

    plot_top, plot_bottom = top - 6, top + row_h * len(categories) - 10
    for t in ticks:
        x = sx(t)
        out.append(f'<line class="gridline" x1="{x:.1f}" x2="{x:.1f}" y1="{plot_top}" '
                   f'y2="{plot_bottom}" stroke-width="1"/>')
        out.append(f'<text class="muted" x="{x:.1f}" y="{plot_bottom + 16}" font-size="11" '
                   f'text-anchor="middle">{fmt(t)}</text>')
    out.append(f'<text class="muted" x="{left + plot_w / 2:.1f}" y="{plot_bottom + 34}" '
               f'font-size="11" text-anchor="middle">{x_label}</text>')

    for i, cat in enumerate(categories):
        y0 = top + i * row_h
        out.append(f'<text class="ink" x="{left - 10}" y="{y0 + group_h / 2 + 4:.1f}" '
                   f'font-size="12" text-anchor="end">{cat}</text>')
        if stacked:
            x = sx(x_start)
            # Segments under a pixel would only draw as slivers; the total
            # label and the tables still carry their values.
            width_of = lambda v: sx(x_start + v) - sx(x_start)
            nonzero = [j for j, s in enumerate(series) if width_of(s[2][i]) >= 1]
            for j, (name, cls, vals) in enumerate(series):
                w = width_of(vals[i])
                if w < 1:
                    continue
                last = j == nonzero[-1]
                seg_w = w if last else max(w - gap, 0.5)
                if last:
                    out.append(f'<path class="{cls}" d="{bar_path(x, y0, seg_w, bar_h)}">'
                               f'<title>{cat}: {name} {fmt(vals[i])}</title></path>')
                else:
                    out.append(f'<rect class="{cls}" x="{x:.1f}" y="{y0}" width="{seg_w:.1f}" '
                               f'height="{bar_h}"><title>{cat}: {name} {fmt(vals[i])}</title></rect>')
                x += w
            out.append(f'<text class="ink2" x="{x + 6:.1f}" y="{y0 + bar_h / 2 + 4:.1f}" '
                       f'font-size="11">{fmt(totals[i])}</text>')
        else:
            for j, (name, cls, vals) in enumerate(series):
                y = y0 + j * (bar_h + gap)
                x0 = sx(x_start)
                w = sx(vals[i]) - x0
                out.append(f'<path class="{cls}" d="{bar_path(x0, y, w, bar_h)}">'
                           f'<title>{cat}, {name}: {fmt(vals[i])}</title></path>')
                out.append(f'<text class="ink2" x="{x0 + w + 6:.1f}" y="{y + bar_h - 3}" '
                           f'font-size="11">{fmt(vals[i])}</text>')
    out.append(f'<line class="baseline" x1="{sx(x_start):.1f}" x2="{sx(x_start):.1f}" '
               f'y1="{plot_top}" y2="{plot_bottom}" stroke-width="1"/>')
    if note:
        out.append(f'<text class="muted" x="16" y="{height - 12}" font-size="11">{note}</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def charts(results, out_dir):
    r = {(s["workload"], s["experiment"]): s for s in results}
    cats = WORKLOADS

    def per_instr(e, key):
        return [(r[(w, e)]["lost"][key] if key in r[(w, e)]["lost"] else r[(w, e)][key]) /
                r[(w, e)]["instructions"] for w in cats]

    stack = hbar_chart(
        "Where the cycles go", "CPI of the baseline pipeline, split by cause",
        cats,
        [("1 per instruction", "base", [1.0] * len(cats)),
         ("load-use stalls", "s1", per_instr("baseline", "load-use")),
         ("mul/div stalls", "s2", per_instr("baseline", "mul/div")),
         ("control-flow flushes", "s3", per_instr("baseline", "control_lost"))],
        stacked=True, fmt=lambda v: f"{v:.2f}", x_label="cycles per instruction",
        note="Forwarding on, 2-bit predictor, 64-entry BTB, 8-entry RAS, 3-cycle multiply, "
             "32-cycle divide.")
    forwarding = hbar_chart(
        "Forwarding", "CPI with the bypass network off and on (2-bit predictor in both)",
        cats,
        [("no forwarding", "s2", [r[(w, "no-forwarding")]["cpi"] for w in cats]),
         ("forwarding", "s1", [r[(w, "baseline")]["cpi"] for w in cats])],
        stacked=False, fmt=lambda v: f"{v:.2f}", x_label="cycles per instruction")
    predictors = hbar_chart(
        "Branch prediction", "Conditional-branch mispredict rate by direction predictor",
        cats,
        [("always not-taken", "s2", [pct(r[(w, "not-taken")]["branch_mispredicts"],
                                         r[(w, "not-taken")]["branches"]) for w in cats]),
         ("BTFN", "s3", [pct(r[(w, "btfn")]["branch_mispredicts"], r[(w, "btfn")]["branches"])
                         for w in cats]),
         ("2-bit counters", "s1", [pct(r[(w, "baseline")]["branch_mispredicts"],
                                       r[(w, "baseline")]["branches"]) for w in cats])],
        stacked=False, fmt=lambda v: f"{v:.0f}%" if v >= 10 or v == 0 else f"{v:.1f}%",
        x_label="mispredicted conditional branches")
    for name, svg in [("cpi_stack.svg", stack), ("forwarding.svg", forwarding),
                      ("predictors.svg", predictors)]:
        open(os.path.join(out_dir, name), "w").write(svg)


# --------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rvsim", default=os.path.join(ROOT, "build", "rvsim"))
    parser.add_argument("--out", default=os.path.join(ROOT, "results"))
    args = parser.parse_args()
    if not os.path.exists(args.rvsim):
        sys.exit(f"{args.rvsim} not found; build first (cmake -S . -B build && cmake --build build)")
    os.makedirs(args.out, exist_ok=True)

    jobs = [(w, c) for w in WORKLOADS for c in CONFIGS]
    with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count()) as pool:
        results = list(pool.map(lambda j: run_one(args.rvsim, *j), jobs))

    with open(os.path.join(args.out, "results.json"), "w") as f:
        json.dump(results, f, indent=1)
    columns = ["workload", "experiment", "forwarding", "predictor", "btb_entries", "ras_entries",
               "mul_latency", "div_latency", "instructions", "cycles", "cpi", "total_lost",
               "load-use", "data-hazard", "mul/div", "control_lost", "branches",
               "branch_mispredicts", "returns", "return_mispredicts", "jals", "jal_misses",
               "bypass_ex_mem", "bypass_mem_wb", "bypass_store_data"]
    with open(os.path.join(args.out, "results.csv"), "w", newline="") as f:
        out = csv.writer(f)
        out.writerow(columns)
        for s in results:
            flat = {**s, **s["config"], **s["lost"]}
            out.writerow([flat[c] for c in columns])

    text, headline = summary(results)
    open(os.path.join(args.out, "summary.md"), "w").write(text)
    charts(results, args.out)
    print(json.dumps(headline, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
